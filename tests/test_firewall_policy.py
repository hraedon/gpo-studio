def test_unknown_tokens_preserved_in_order_and_refused_on_write() -> None:
    records = parse(native_bytes())
    rule = records[8]
    assert isinstance(rule.value, str)
    value = rule.value.replace("Action=Allow|", "Action=Allow|Future=one|") + "Future=two|"
    result = from_registry_records(records[:8] + [replace(rule, value=value)] + records[9:])
    unknown = result.policy.rules[0].unknown_tokens
    assert unknown == (UnknownFirewallToken(1, "Future=one"), UnknownFirewallToken(8, "Future=two"))
    with pytest.raises(FirewallValidationError) as error:
        to_registry_settings(result.policy)
    assert error.value.issues[0].code == "firewall_unknown_tokens"
    assert result.policy.validate() == error.value.issues


