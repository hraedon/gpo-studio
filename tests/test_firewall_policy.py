def test_native_parse_matches_every_typed_field() -> None:
    records = parse(native_bytes())
    assert len(records) == 25
    result = from_registry_records(records)
    assert result.unrecognised_records == ()
    assert len(result.policy.rules) == 13  # A parser returning nothing cannot pass.
    assert result.policy == expected_policy()
    assert result.policy.validate() == ()


def test_emit_independent_model_matches_native_record_bytes() -> None:
    emitted = to_registry_settings(expected_policy())
    native = parse(native_bytes())
    assert len(emitted) == len(native) == 25
    assert all(r.side == "computer" and r.hive == "HKLM" for r in emitted)
    # Compare raw native record slices, not just a parse/serialize tautology.
    # Native order is different; each one-record serialization supplies only
    # the header followed by that native record's exact UTF-16 wire bytes.
    by_identity = {(r.key, r.value_name): r for r in emitted}
    offset = 8
    native_chunks = []
    for record in native:
        chunk = serialize([by_identity[(record.key, record.value_name)]])[8:]
        assert native_bytes()[offset : offset + len(chunk)] == chunk
        native_chunks.append(chunk)
        offset += len(chunk)
    assert offset == len(native_bytes())
    assert b"PReg\x01\x00\x00\x00" + b"".join(native_chunks) == native_bytes()
    assert serialize(emitted) == serialize(native)
    assert serialize(emitted) != native_bytes()  # Documented record-order difference.
    assert parse(serialize(emitted)) == sorted(
        native, key=lambda r: (r.key.casefold(), r.value_name.casefold())
    )


