def test_sanitizer_redacts_synthetic_estate_identities(tmp_path: Path) -> None:
    import shutil

    source = tmp_path / "raw"
    shutil.copytree(FIXTURE, source)
    replacements = (
        ("zz-studio-dc.studio.example", "zz-capture-dc.lab.example"),
        ("studio.example", "lab.example"),
        ("STUDIO", "LAB"),
        ("11111111-1111-4111-8111-111111111111", "aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa"),
        ("22222222-2222-4222-8222-222222222222", "bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb"),
        ("33333333-3333-4333-8333-333333333333", "cccccccc-cccc-4ccc-8ccc-cccccccccccc"),
        ("S-1-5-21-0000000000-0000000000-0000000000", "S-1-5-21-1010101010-2020202020-3030303030"),
        ("zz-studio-firewall-native", "zz-capture-gpo"),
        ("01 00 04 80 00 00 00 00", "AA BB CC DD"),
    )
    for path in source.rglob("*"):
        if not path.is_file() or path.suffix not in (".xml", ".json"):
            continue
        raw = path.read_bytes()
        encoding = "utf-16" if raw.startswith((b"\xff\xfe", b"\xfe\xff")) else "utf-8"
        text = raw.decode(encoding)
        for old, new in replacements:
            text = text.replace(old, new)
        path.write_bytes(text.encode(encoding))
    backup = source / "backup/{33333333-3333-4333-8333-333333333333}"
    backup.rename(source / "backup/{cccccccc-cccc-4ccc-8ccc-cccccccccccc}")
    module = runpy.run_path(str(ROOT / "scripts/plan-033/sanitize-firewall-fixtures.py"))
    destination = tmp_path / "sanitized"
    module["sanitize"](source, destination)
    assert (destination / "Registry.pol").read_bytes() == native_bytes()
    assert next(destination.rglob("registry.pol")).read_bytes() == native_bytes()
    for path in destination.rglob("*"):
        if not path.is_file() or path.suffix not in (".xml", ".json"):
            continue
        raw = path.read_bytes()
        text = raw.decode("utf-16" if raw.startswith((b"\xff\xfe", b"\xfe\xff")) else "utf-8-sig")
        for _, synthetic_original in replacements:
            if synthetic_original == "LAB":
                import re

